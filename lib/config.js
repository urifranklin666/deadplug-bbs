'use strict';

const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const DEFAULTS = {
  bbsName: 'DEADPLUG BBS',
  host: '127.0.0.1',
  webPort: 7683,
  telnetPort: 2323,
  sshPort: 2222,
  publicUrl: '',
  dataDir: './data',
  sessionSecret: '',
  maxUploadBytes: 50 * 1024 * 1024,
  idleTimeoutMinutes: 15,
  maxSessionsPerIp: 6,
  trustProxy: false,
  sshHostKey: '',
};

function parseArgs(argv) {
  const out = {};
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (!arg.startsWith('--')) continue;
    const key = arg.slice(2);
    if (key === 'help' || key === 'version') {
      out[key] = true;
      continue;
    }
    const eq = key.indexOf('=');
    if (eq !== -1) {
      out[key.slice(0, eq)] = key.slice(eq + 1);
    } else if (argv[i + 1] && !argv[i + 1].startsWith('--')) {
      out[key] = argv[++i];
    } else {
      out[key] = true;
    }
  }
  return out;
}

function number(value, fallback) {
  const n = Number(value);
  return Number.isFinite(n) && n > 0 ? n : fallback;
}

/**
 * Load the installation config. The file is infrastructure-only: ports,
 * paths, secrets and limits. Presentation settings live in the settings table
 * so the sysop can change them from the admin panel without a restart.
 */
function loadConfig(argv = process.argv.slice(2), env = process.env) {
  const args = parseArgs(argv);
  const configPath = path.resolve(
    args.config || env.BBS_CONFIG || path.join(process.cwd(), 'config.json')
  );

  let fileConfig = {};
  if (fs.existsSync(configPath)) {
    try {
      fileConfig = JSON.parse(fs.readFileSync(configPath, 'utf8'));
    } catch (err) {
      throw new Error(`Cannot parse ${configPath}: ${err.message}`);
    }
  } else if (args.config || env.BBS_CONFIG) {
    throw new Error(`Config file not found: ${configPath}`);
  }

  const config = { ...DEFAULTS, ...fileConfig };

  // CLI flags win over the file.
  if (args['data-dir']) config.dataDir = args['data-dir'];
  if (args['web-port']) config.webPort = number(args['web-port'], config.webPort);
  if (args['telnet-port']) config.telnetPort = number(args['telnet-port'], config.telnetPort);
  if (args['ssh-port']) config.sshPort = number(args['ssh-port'], config.sshPort);
  if (args.host) config.host = String(args.host);
  if (args['public-url']) config.publicUrl = String(args['public-url']);

  config.configPath = configPath;
  config.dataDir = path.resolve(path.dirname(configPath), config.dataDir);
  config.webPort = number(config.webPort, DEFAULTS.webPort);
  config.telnetPort = number(config.telnetPort, DEFAULTS.telnetPort);
  config.sshPort = number(config.sshPort, DEFAULTS.sshPort);
  config.idleTimeoutMinutes = number(config.idleTimeoutMinutes, DEFAULTS.idleTimeoutMinutes);
  config.maxUploadBytes = number(config.maxUploadBytes, DEFAULTS.maxUploadBytes);
  config.maxSessionsPerIp = number(config.maxSessionsPerIp, DEFAULTS.maxSessionsPerIp);

  if (!config.publicUrl) {
    const port = config.webPort === 80 ? '' : `:${config.webPort}`;
    config.publicUrl = `http://${config.host === '0.0.0.0' ? 'localhost' : config.host}${port}`;
  }
  config.publicUrl = config.publicUrl.replace(/\/+$/, '');

  if (!config.sessionSecret) {
    // A config generated by install.sh always has a secret. For a manual
    // `node server.js` run, generate one and persist it next to the config.
    config.sessionSecret = crypto.randomBytes(32).toString('hex');
    if (fs.existsSync(configPath)) {
      const updated = { ...fileConfig, sessionSecret: config.sessionSecret };
      fs.writeFileSync(configPath, JSON.stringify(updated, null, 2) + '\n', { mode: 0o600 });
      console.warn('[config] generated a new sessionSecret and saved it to', configPath);
    }
  }

  config.sshHostKey = config.sshHostKey
    ? path.resolve(path.dirname(configPath), config.sshHostKey)
    : path.join(config.dataDir, 'ssh_host_rsa_key');
  config.filesDir = path.join(config.dataDir, 'files');
  config.doorsDir = path.join(config.dataDir, 'doors');

  for (const dir of [config.dataDir, config.filesDir, config.doorsDir]) {
    fs.mkdirSync(dir, { recursive: true, mode: 0o700 });
  }

  return config;
}

module.exports = { loadConfig, parseArgs, DEFAULTS };
